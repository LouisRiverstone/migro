// Package oracle registers Oracle Database using the pure-Go go-ora driver (no cgo).
//
// DSN format: oracle://user:password@host:1521/service_name
//
// Identifiers are upper-cased to match the GORM Oracle driver's default naming.
package oracle

import (
	"fmt"

	"github.com/LouisRiverstone/migro/dialect"
	oracle "github.com/godoes/gorm-oracle"
	"gorm.io/gorm"
)

type oraDialect struct{ dialect.Base }

func init() { dialect.Register(&oraDialect{}, "oracledb") }

func (d *oraDialect) Name() string                        { return "oracle" }
func (d *oraDialect) Dialector(dsn string) gorm.Dialector { return oracle.Open(dsn) }
func (d *oraDialect) DriverName() string                  { return "oracle" }
func (d *oraDialect) FromConn(conn gorm.ConnPool) gorm.Dialector {
	return oracle.New(oracle.Config{Conn: conn})
}
func (d *oraDialect) Quote(i string) string { return dialect.QuoteWith(i, `"`, `"`, true) }

func (d *oraDialect) ColumnType(c dialect.Column) string {
	switch c.Kind {
	case dialect.KindString, dialect.KindEnum:
		return fmt.Sprintf("VARCHAR2(%d)", c.Length)
	case dialect.KindText, dialect.KindJSON:
		return "CLOB"
	case dialect.KindSmallInt:
		return "NUMBER(5)"
	case dialect.KindInteger:
		return "NUMBER(10)"
	case dialect.KindBigInt:
		return "NUMBER(19)"
	case dialect.KindBoolean:
		return "NUMBER(1)"
	case dialect.KindFloat:
		return "BINARY_FLOAT"
	case dialect.KindDouble:
		return "BINARY_DOUBLE"
	case dialect.KindDecimal:
		return fmt.Sprintf("NUMBER(%d,%d)", c.Precision, c.Scale)
	case dialect.KindDate:
		return "DATE"
	case dialect.KindTime:
		return "VARCHAR2(15)" // Oracle has no TIME type
	case dialect.KindDateTime:
		return "TIMESTAMP"
	case dialect.KindStamp:
		return "TIMESTAMP WITH TIME ZONE"
	case dialect.KindUUID:
		return "VARCHAR2(36)"
	case dialect.KindBinary:
		return "BLOB"
	}
	return ""
}

func (d *oraDialect) AutoIncrement(big bool) string {
	if big {
		return "NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
	}
	return "NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
}

func (d *oraDialect) AddColumnKeyword() string { return "ADD" }

func (d *oraDialect) RenameTable(from, to string) string {
	return fmt.Sprintf("ALTER TABLE %s RENAME TO %s", d.Quote(from), d.Quote(to))
}
func (d *oraDialect) RenameColumn(t, from, to string) string {
	return fmt.Sprintf("ALTER TABLE %s RENAME COLUMN %s TO %s", d.Quote(t), d.Quote(from), d.Quote(to))
}
func (d *oraDialect) DropIndex(_, name string) string { return "DROP INDEX " + d.Quote(name) }
func (d *oraDialect) DropConstraint(t, name string) string {
	return fmt.Sprintf("ALTER TABLE %s DROP CONSTRAINT %s", d.Quote(t), d.Quote(name))
}
func (d *oraDialect) DropForeign(t, name string) string { return d.DropConstraint(t, name) }

// Oracle implicitly commits DDL.
func (d *oraDialect) TransactionalDDL() bool { return false }
