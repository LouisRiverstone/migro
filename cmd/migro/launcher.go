func fileExists(p string) bool { _, err := os.Stat(p); return err == nil }

// findRoot walks up from dir to the directory containing go.mod.
func findRoot(dir string) (string, error) {
	for d := dir; ; d = filepath.Dir(d) {
		if fileExists(filepath.Join(d, "go.mod")) {
			return d, nil
		}
		if filepath.Dir(d) == d {
			return "", errors.New("go.mod not found")
		}
	}
}

func readModulePath(root string) (string, error) {
	b, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return "", err
	}
	for _, line := range strings.Split(string(b), "\n") {
		if rest, ok := strings.CutPrefix(strings.TrimSpace(line), "module "); ok {
			return strings.Trim(strings.TrimSpace(rest), `"`), nil
		}
	}
	return "", errors.New("no module line in go.mod")
}

var dialectPackages = map[string]string{
	"postgres": "postgres", "postgresql": "postgres", "pg": "postgres", "pgx": "postgres", "cockroachdb": "postgres", "cockroach": "postgres", "redshift": "postgres",
	"mysql": "mysql", "mariadb": "mysql",
	"sqlite": "sqlite", "sqlite3": "sqlite",
	"sqlserver": "sqlserver", "mssql": "sqlserver",
	"oracle": "oracle", "oracledb": "oracle",
}

// dialectImports returns the dialect packages needed by every configured connection.
func dialectImports(environ []string) ([]string, error) {
	seen := map[string]bool{}
	for _, kv := range environ {
		k, v, _ := strings.Cut(kv, "=")
		if k != "MIGRO_DIALECT" && !(strings.HasPrefix(k, "MIGRO_") && strings.HasSuffix(k, "_DIALECT")) {
			continue
		}
		if v == "" {
			continue
		}
		pkg, ok := dialectPackages[strings.ToLower(v)]
		if !ok {
			return nil, fmt.Errorf("%s=%q is not a supported dialect", k, v)
		}
		seen[pkg] = true
	}
	if len(seen) == 0 {
		return nil, errors.New("no database configured: set MIGRO_DIALECT and MIGRO_DSN (environment or .env)")
	}
	out := make([]string, 0, len(seen))
	for p := range seen {
		out = append(out, "github.com/LouisRiverstone/migro/dialect/"+p)
	}
	sort.Strings(out)
	return out, nil
}

// hasGoFiles reports whether dir contains non-test Go files (a package to import).
func hasGoFiles(dir string) bool {
	files, _ := filepath.Glob(filepath.Join(dir, "*.go"))
	for _, f := range files {
		if !strings.HasSuffix(f, "_test.go") {
			return true
		}
	}
	return false
}

// discoverModels lists exported struct types in dir, skipping any whose doc comment contains "migro:ignore".
func discoverModels(dir string) (pkg string, names []string, err error) {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool { return !strings.HasSuffix(fi.Name(), "_test.go") }, parser.ParseComments)
	if err != nil {
		return "", nil, err
	}
	for name, p := range pkgs {
		pkg = name
		for _, f := range p.Files {
			for _, decl := range f.Decls {
				gd, ok := decl.(*ast.GenDecl)
				if !ok || gd.Tok != token.TYPE {
					continue
				}
				for _, spec := range gd.Specs {
					ts := spec.(*ast.TypeSpec)
					st, isStruct := ts.Type.(*ast.StructType)
					if !isStruct || !ts.Name.IsExported() || st.Fields == nil || len(st.Fields.List) == 0 {
						continue
					}
					doc := ts.Doc
					if doc == nil {
						doc = gd.Doc
					}
					if doc != nil && strings.Contains(doc.Text(), "migro:ignore") {
						continue
					}
					names = append(names, ts.Name.Name)
				}
			}
		}
	}
	sort.Strings(names)
	return pkg, names, nil
}

type runnerSpec struct {
	Dialects   []string
	Blank      []string // packages imported for their init() side effects
	ModelsPkg  string   // import path, "" when not needed
	ModelsName string   // package name
	Models     []string
}

func renderMain(s runnerSpec) string {
	var b strings.Builder
	b.WriteString("// Code generated by migro; DO NOT EDIT. Safe to delete.\npackage main\n\nimport (\n\t\"os\"\n\n\t\"github.com/LouisRiverstone/migro/console\"\n")
	for _, d := range s.Dialects {
		fmt.Fprintf(&b, "\t_ %q\n", d)
	}
	for _, p := range s.Blank {
		fmt.Fprintf(&b, "\t_ %q\n", p)
	}
	if s.ModelsPkg != "" {
		fmt.Fprintf(&b, "\t%s %q\n", s.ModelsName, s.ModelsPkg)
	}
	b.WriteString(")\n\nfunc main() {\n\tapp, err := console.FromEnv(\".\")\n\tif err != nil {\n\t\tos.Stderr.WriteString(\"ERROR  \" + err.Error() + \"\\n\")\n\t\tos.Exit(console.ExitError)\n\t}\n")
	if len(s.Models) > 0 {
		b.WriteString("\tapp.Models = []any{\n")
		for _, m := range s.Models {
			fmt.Fprintf(&b, "\t\t&%s.%s{},\n", s.ModelsName, m)
		}
		b.WriteString("\t}\n")
	}
	b.WriteString("\tos.Exit(app.Main(os.Args[1:]))\n}\n")
	return b.String()
}

func runInModule(app *console.App, root string, args []string) int {
	fail := func(format string, a ...any) int {
		fmt.Fprintf(os.Stderr, "ERROR  "+format+"\n", a...)
		return console.ExitError
	}
	module, err := readModulePath(root)
	if err != nil {
		return fail("%v", err)
	}
	dialects, err := dialectImports(os.Environ())
	if err != nil {
		return fail("%v", err)
	}
	spec := runnerSpec{Dialects: dialects}
	for _, dir := range []string{pick(app.MigrationsDir, "database/migrations"), pick(app.SeedersDir, "database/seeders")} {
		if hasGoFiles(filepath.Join(root, dir)) {
			spec.Blank = append(spec.Blank, module+"/"+filepath.ToSlash(dir))
		}
	}
	if args[0] == "migration:diff" {
		dir := pick(app.ModelsDir, "app/models")
		pkg, names, err := discoverModels(filepath.Join(root, dir))
		if err != nil || len(names) == 0 {
			return fail("no models found in %s (exported structs; add `// migro:ignore` to skip one)", dir)
		}
		spec.ModelsPkg, spec.ModelsName, spec.Models = module+"/"+filepath.ToSlash(dir), pkg, names
	}

	tmp, err := os.MkdirTemp(root, "_migro_run_")
	if err != nil {
		return fail("cannot create the runner directory: %v", err)
	}
	defer os.RemoveAll(tmp)
	if err := os.WriteFile(filepath.Join(tmp, "main.go"), []byte(renderMain(spec)), 0o644); err != nil {
		return fail("%v", err)
	}

	// Build first, then run: `go run` would print "exit status N" for every non-zero exit code.
	// -mod=mod lets go add the database driver to go.mod/go.sum if your app does not import it yet.
	bin := filepath.Join(tmp, "runner")
	if runtime.GOOS == "windows" {
		bin += ".exe"
	}
	build := exec.Command("go", "build", "-mod=mod", "-o", bin, "./"+filepath.Base(tmp))
	build.Dir = root
	build.Stdout, build.Stderr = os.Stdout, os.Stderr
	if err := build.Run(); err != nil {
		var ee *exec.ExitError
		if errors.As(err, &ee) {
			fmt.Fprintln(os.Stderr, "ERROR  could not compile your project; fix the errors above (try `go mod tidy` if a module is missing)")
			return console.ExitError
		}
		return fail("could not run `go build` (is Go installed and on PATH?): %v", err)
	}

	cmd := exec.Command(bin, args...)
	cmd.Dir = root
	cmd.Stdin, cmd.Stdout, cmd.Stderr = os.Stdin, os.Stdout, os.Stderr
	// Let the child handle Ctrl-C so this process survives long enough to clean up the runner directory.
	sig := make(chan os.Signal, 1)
	signal.Notify(sig, os.Interrupt)
	defer signal.Stop(sig)
	if err := cmd.Run(); err != nil {
		var ee *exec.ExitError
		if errors.As(err, &ee) {
			return ee.ExitCode()
		}
		return fail("could not start the runner: %v", err)
	}
	return console.ExitOK
}

func pick(v, fallback string) string {
	if v != "" {
		return v
	}
	return fallback
}
