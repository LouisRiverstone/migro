func users(t *schema.Table) {
	t.Increments("id")
	t.String("email", 120).NotNull().Unique()
	t.Boolean("active").NotNull().Default(true)
	t.Enum("role", "admin", "user").Default("user")
	t.Decimal("balance", 10, 2)
	t.Timestamps()
}

func TestCreateSQLPerDialect(t *testing.T) {
	cases := map[string][]string{
		"postgres":    {`"id" serial primary key`, `"active" boolean DEFAULT TRUE NOT NULL`, `CHECK ("role" IN ('admin', 'user'))`, `"created_at" timestamptz`, `numeric(10,2)`},
		"cockroachdb": {`"id" serial primary key`},
		"redshift":    {`integer identity(1,1) primary key`},
		"mysql":       {"`id` int unsigned not null auto_increment primary key", "`role` enum('admin','user') DEFAULT 'user'", "`active` tinyint(1) DEFAULT 1 NOT NULL"},
		"mariadb":     {"`email` varchar(120) NOT NULL"},
		"sqlite":      {`"id" integer primary key autoincrement`},
		"sqlserver":   {"[id] int identity(1,1) not null primary key", "[active] bit DEFAULT 1 NOT NULL", "nvarchar(120)"},
		"oracle":      {`"ID" NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`, `"ACTIVE" NUMBER(1) DEFAULT 1 NOT NULL`, `VARCHAR2(120)`},
	}
	for name, wants := range cases {
		t.Run(name, func(t *testing.T) {
			d, err := dialect.Get(name)
			if err != nil {
				t.Fatal(err)
			}
			stmts, err := schema.CreateSQL(d, "users", users)
			if err != nil {
				t.Fatal(err)
			}
			sql := strings.Join(stmts, "\n")
			for _, w := range wants {
				if !strings.Contains(sql, w) {
					t.Errorf("want %q in:\n%s", w, sql)
				}
			}
		})
	}
}

func TestIndexUnsupportedOnRedshift(t *testing.T) {
	d, _ := dialect.Get("redshift")
	_, err := schema.CreateSQL(d, "x", func(t *schema.Table) { t.Integer("a").Index() })
	if !errors.Is(err, migro.ErrUnsupportedFeature) {
		t.Fatalf("want UNSUPPORTED_FEATURE, got %v", err)
	}
}

func TestInvalidInputs(t *testing.T) {
	d, _ := dialect.Get("postgres")
	bad := map[string]func(*schema.Table){
		"no columns": func(*schema.Table) {},
		"bad fk action": func(t *schema.Table) {
			t.Integer("a")
			t.Foreign("a").References("b", "id").OnDelete("CASCADE; DROP TABLE x")
		},
		"fk no ref":   func(t *schema.Table) { t.Integer("a"); t.Foreign("a") },
		"bad default": func(t *schema.Table) { t.Integer("a").Default([]int{1}) },
		"empty enum":  func(t *schema.Table) { t.Enum("e") },
	}
	for name, fn := range bad {
		t.Run(name, func(t *testing.T) {
			if _, err := schema.CreateSQL(d, "x", fn); migro.CodeOf(err) == "" {
				t.Fatalf("want migro error, got %v", err)
			}
		})
	}
}

func TestQuotingEscapesIdentifiers(t *testing.T) {
	d, _ := dialect.Get("postgres")
	stmts, err := schema.CreateSQL(d, `we"ird`, func(t *schema.Table) { t.Integer(`a"b`) })
	if err != nil || !strings.Contains(stmts[0], `"we""ird"`) || !strings.Contains(stmts[0], `"a""b"`) {
		t.Fatalf("identifiers not escaped: %v %v", stmts, err)
	}
}

func TestAlterSQLSQLiteLimits(t *testing.T) {
	d, _ := dialect.Get("sqlite")
	_, err := schema.AlterSQL(d, "posts", func(t *schema.Table) { t.Foreign("user_id").References("users", "id") })
	if !errors.Is(err, migro.ErrUnsupportedFeature) {
		t.Fatalf("want UNSUPPORTED_FEATURE, got %v", err)
	}
	stmts, err := schema.AlterSQL(d, "posts", func(t *schema.Table) { t.Unique("slug") })
	if err != nil || !strings.HasPrefix(stmts[0], "CREATE UNIQUE INDEX") {
		t.Fatalf("sqlite unique should become index: %v %v", stmts, err)
	}
}

func TestLongIdentifierTruncated(t *testing.T) {
	d, _ := dialect.Get("postgres")
	long := strings.Repeat("c", 70)
	stmts, _ := schema.CreateSQL(d, "t", func(t *schema.Table) { t.Integer(long).Index() })
	for _, s := range stmts {
		if strings.HasPrefix(s, "CREATE INDEX") {
			name := strings.Split(s, `"`)[1]
			if len(name) > 63 {
				t.Fatalf("index name too long (%d)", len(name))
			}
		}
	}
}

func TestLiveSchemaLifecycle(t *testing.T) {
	ctx := context.Background()
	db := testdb.Open(t)
	s := schema.New(db)
	must := func(err error) {
		t.Helper()
		if err != nil {
			t.Fatal(err)
		}
	}
	must(s.CreateTable(ctx, "sl_users", users))
	must(s.CreateTable(ctx, "sl_posts", func(t *schema.Table) {
		t.BigIncrements("id")
		t.Integer("user_id").NotNull()
		t.String("title")
		t.Foreign("user_id").References("sl_users", "id").OnDelete("cascade")
		t.Index("title")
		t.SoftDeletes()
	}))
	ok, _ := s.HasTable(ctx, "sl_posts")
	if !ok {
		t.Fatal("sl_posts should exist")
	}
	must(s.AlterTable(ctx, "sl_posts", func(t *schema.Table) { t.Text("body") }))
	if ok, _ := s.HasColumn(ctx, "sl_posts", "body"); !ok {
		t.Fatal("body column missing after alter")
	}
	must(s.RenameTable(ctx, "sl_posts", "sl_articles"))
	must(s.DropTableIfExists(ctx, "sl_articles"))
	must(s.DropTableIfExists(ctx, "sl_users"))
	must(s.DropTableIfExists(ctx, "sl_users")) // idempotent
	if ok, _ := s.HasTable(ctx, "sl_users"); ok {
		t.Fatal("sl_users should be gone")
	}
}
